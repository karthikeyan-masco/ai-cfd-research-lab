"""Versioned, reproducible benchmark challenge definitions.

References are computed by the existing deterministic physics functions,
not generated by a language model. These are reference calculations,
not independent experimental validation.
"""
from __future__ import annotations

from dataclasses import dataclass
from types import MappingProxyType
from typing import Mapping

from ai_cfd_lab.benchmarks.shocks import normal_shock, oblique_shock_properties
from ai_cfd_lab.benchmarks.sod import sod_exact


@dataclass(frozen=True)
class Challenge:
    id: str
    title: str
    prompt: str
    kind: str
    inputs: Mapping[str, float]
    output_keys: tuple[str, ...]
    version: int = 1

    def reference(self) -> "ChallengeResult":
        params = dict(self.inputs)
        if self.kind == "normal_shock":
            values = normal_shock(params["M1"], params["gamma"])
        elif self.kind == "oblique_shock":
            values = oblique_shock_properties(params["M1"], params["theta_deg"], params["gamma"])
        elif self.kind == "sod":
            values = sod_exact(params["x"], params["time"], params["x0"], params["gamma"])
        else:
            raise ValueError(f"Unsupported benchmark kind: {self.kind}")
        return ChallengeResult(self.id, self.version, {k: float(values[k]) for k in self.output_keys})


@dataclass(frozen=True)
class ChallengeResult:
    challenge_id: str
    version: int
    reference_values: Mapping[str, float]


def all_challenges() -> tuple[Challenge, ...]:
    return (
        Challenge(
            id="normal-shock-m2", title="Mach 2 normal shock",
            prompt="For a calorically perfect gas with gamma=1.4 and M1=2, calculate downstream Mach and static property ratios.",
            kind="normal_shock", inputs=MappingProxyType({"M1": 2.0, "gamma": 1.4}),
            output_keys=("M2", "p2_p1", "rho2_rho1", "T2_T1"),
        ),
        Challenge(
            id="oblique-shock-m2-theta10", title="Weak attached oblique shock",
            prompt="For M1=2, gamma=1.4 and a 10 degree compression turn, compute the weak attached shock angle and downstream properties.",
            kind="oblique_shock", inputs=MappingProxyType({"M1": 2.0, "theta_deg": 10.0, "gamma": 1.4}),
            output_keys=("beta_deg", "Mn1", "M2", "p2_p1", "rho2_rho1", "T2_T1"),
        ),
        Challenge(
            id="sod-x070-t020", title="Standard Sod shock tube sample",
            prompt="Evaluate the exact ideal-gas Sod solution at x=0.7, t=0.2, initial discontinuity x0=0.5, gamma=1.4. Return density, velocity and pressure.",
            kind="sod", inputs=MappingProxyType({"x": 0.7, "time": 0.2, "x0": 0.5, "gamma": 1.4}),
            output_keys=("rho", "u", "p"),
        ),
    )


def get_challenge(challenge_id: str) -> Challenge:
    for challenge in all_challenges():
        if challenge.id == challenge_id:
            return challenge
    raise KeyError(f"Unknown challenge: {challenge_id}")
